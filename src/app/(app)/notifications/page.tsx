import type { Metadata } from "next";
import { requireUser } from "@/lib/auth/account";
import { getNotifications } from "@/lib/data/workspace";
import { PageHeader } from "@/components/dashboard/page-header";
import { NotificationsView } from "@/components/notifications/notifications-view";

export const metadata: Metadata = {
  title: "Notifications",
  description: "Payment, invoice, reminder, and security updates from your workspace.",
};

export default async function NotificationsPage() {
  const account = await requireUser();
  const user = account.user!;
  const result = await getNotifications(account.supabase, user.id, 200);

  return (
    <div className="mx-auto max-w-4xl space-y-5 px-4 py-6 sm:px-6 lg:px-8 lg:py-8">
      <PageHeader
        eyebrow="Notifications"
        title="Everything that happened"
        description="Updates are generated by real events in your workspace: captures, agent actions, reminders, and sign in activity."
      />

      <NotificationsView
        notifications={result.notifications}
        databaseError={result.error}
      />
    </div>
  );
}
